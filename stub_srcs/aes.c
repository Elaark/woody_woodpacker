static const uint8_t rcon_table[11] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
};

void RotWord(uint8_t word[4]) {
    uint8_t k = word[0];
    word[0] = word[1];
    word[1] = word[2];
    word[2] = word[3];
    word[3] = k;
}

void Subword(uint8_t word[4]) {
    word[0] = sbox[word[0]];
    word[1] = sbox[word[1]];
    word[2] = sbox[word[2]];
    word[3] = sbox[word[3]];
}

void KeyExpansion(const uint8_t k[16], uint8_t *round_keys) {
    for (int i = 0; i < 16; i++) {
        round_keys[i] = k[i];
    }
    uint8_t tmp[4];
    int bytes_generated = 16;
    int rcon_iteration = 1;

    while (bytes_generated < 176) {
        for (int i = 0; i < 4; i++) {
            tmp[i] = round_keys[bytes_generated - 4 + i];
        }
        if (bytes_generated % 16 == 0) {
            RotWord(tmp);
            Subword(tmp);
            tmp[0] ^= rcon_table[rcon_iteration++];
        }
        for (int i = 0; i < 4; i++) {
            round_keys[bytes_generated + i] = round_keys[bytes_generated - 16 + i] ^ tmp[i];
        }
        bytes_generated += 4;
    }
}

int aes_encrypt_buffer(uint8_t *buf, size_t size, const uint8_t *key, const uint8_t *initial_iv) {
    if (!buf || !key || !initial_iv || size == 0 || size % 16 != 0) {
        errno = EINVAL;
        return -1;
    }

    uint8_t round_keys[176];
    KeyExpansion(key, round_keys);

    uint8_t current_iv[16];
    memcpy(current_iv, initial_iv, 16);

    aes_encrypt_cbc_asm(buf, size, round_keys, current_iv);
    return 0;
}

int aes_decrypt_buffer(uint8_t *buf, size_t size, const uint8_t *key, const uint8_t *initial_iv) {
    if (!buf || !key || !initial_iv || size == 0 || size % 16 != 0) {
        errno = EINVAL;
        return -1;
    }

    uint8_t round_keys[176];
    KeyExpansion(key, round_keys);

    uint8_t current_iv[16];
    memcpy(current_iv, initial_iv, 16);

    aes_decrypt_cbc_asm(buf, size, round_keys, current_iv);
    return 0;
}




int encrypt_buffer_inplace(uint8_t *src, size_t original_size, uint8_t **out_extra_block, size_t *out_extra_len, const uint8_t *key, const uint8_t *iv) {
    
    if (!src || original_size == 0 || !out_extra_block || !out_extra_len || !key || !iv)
        return -1;

    *out_extra_block = NULL;
    *out_extra_len = 0;

    size_t remainder = original_size % 16;
    size_t full_blocks_len = original_size - remainder;

    uint8_t current_iv[16];
    memcpy(current_iv, iv, 16);

    if (full_blocks_len > 0) {
        if (aes_encrypt_buffer(src, full_blocks_len, key, current_iv) != 0) {
            return -1;
        }
        memcpy(current_iv, src + full_blocks_len - 16, 16);
    }

    if (remainder > 0) {
        size_t pad_len = 16 - remainder;
        uint8_t *extra_block = malloc(16);
        if (!extra_block)
            return -1;

        memcpy(extra_block, src + full_blocks_len, remainder);
        memset(extra_block + remainder, (uint8_t)pad_len, pad_len);

        // Chiffrementdu dernier bloc avec l'IV mis à jour
        if (aes_encrypt_buffer(extra_block, 16, key, current_iv) != 0) {
            free(extra_block);
            return -1;
        }

        *out_extra_block = extra_block;
        *out_extra_len = 16;
    }

    return 0;
}